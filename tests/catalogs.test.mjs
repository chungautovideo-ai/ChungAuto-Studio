import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createCatalogService } from '../src/services/catalogs.mjs';
test('Catalog import is repeatable, workspace scoped and preserves edited source versions', t => {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'contentos-catalog-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const source=path.join(root,'aiev');
  for(const folder of ['video-styles','prompts'])fs.mkdirSync(path.join(source,'assets',folder),{recursive:true});
  fs.mkdirSync(path.join(root,'config'));
  fs.writeFileSync(path.join(root,'config/sources.local.json'),JSON.stringify({aievRoot:source}));
  const style=path.join(source,'assets/video-styles/video-styles.json');
  fs.writeFileSync(style,JSON.stringify({styles:[{id:'paper',name:'Paper',art:'Paper layers',secret:'excluded'}]}));
  fs.writeFileSync(path.join(source,'assets/prompts/prompts.json'),JSON.stringify([{id:'brief',name:'Brief',content:'Write a brief'}]));
  const service=createCatalogService(root);
  assert.equal(service.preview().length,2);
  assert.equal(service.preview()[0].payload.secret,undefined);
  assert.equal(service.import('one').imported,2);
  assert.equal(service.import('one').imported,0);
  assert.equal(service.list('two').entries.length,0);
  const first=service.list('one').entries;
  const brief=service.brief('one',{styleId:first[0].id,promptId:first[1].id});assert.equal(brief.entries.length,2);assert.equal(brief.entries[0].payload.art,'Paper layers');
  brief.entries[0].payload.art='Mutated';assert.equal(service.brief('one',{styleId:first[0].id}).entries[0].payload.art,'Paper layers');
  assert.throws(()=>service.brief('two',{styleId:first[0].id}),/workspace/);
  assert.throws(()=>service.brief('one',{promptId:first[0].id}),/workspace/);
  assert.throws(()=>service.brief('one','bad'),/hợp lệ/);
  fs.writeFileSync(style,JSON.stringify({styles:[{id:'paper',name:'Paper',art:'Updated layers'}]}));
  assert.equal(service.import('one').imported,1);
  assert.equal(service.list('one').entries.length,3);
  assert.equal(service.brief('one',{styleId:first[0].id}).entries[0].payload.art,'Paper layers');
  assert.throws(()=>service.list('../escape'));
});

test('catalog selection pins preview source and workspace and only imports selected identities',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'cos-catalog-plan-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const source=path.join(root,'aiev');
 fs.mkdirSync(path.join(source,'assets/video-styles'),{recursive:true});fs.mkdirSync(path.join(source,'assets/prompts'),{recursive:true});fs.mkdirSync(path.join(root,'config'));
 fs.writeFileSync(path.join(root,'config/sources.local.json'),JSON.stringify({aievRoot:source}));
 fs.writeFileSync(path.join(source,'assets/video-styles/video-styles.json'),JSON.stringify({styles:[{id:'one',name:'One',art:'Original'}]}));
 const promptFile=path.join(source,'assets/prompts/prompts.json');fs.writeFileSync(promptFile,JSON.stringify([{id:'two',name:'Two',content:'Draft'}]));
 const service=createCatalogService(root),plan=service.plan('one');assert.equal(plan.entries.length,2);assert.ok(plan.entries.every(e=>!e.duplicate));
 const selection={workspaceId:'one',fingerprint:plan.fingerprint,ids:[plan.entries[0].id]};
 assert.throws(()=>service.import('two',selection),/Workspace/);
 assert.throws(()=>service.import('one',null),/không hợp lệ/);
 assert.throws(()=>service.import('one',{...selection,ids:['missing']}),/không có/);
 assert.throws(()=>service.import('one',{...selection,ids:[]}),/danh sách/);
 assert.throws(()=>service.import('one',{...selection,ids:[selection.ids[0],selection.ids[0]]}),/danh sách/);
 assert.equal(service.import('one',selection).imported,1);assert.equal(service.list('one').entries.length,1);
 assert.equal(service.plan('one').entries.filter(e=>e.duplicate).length,1);assert.equal(service.import('one',selection).skipped,1);
 fs.writeFileSync(promptFile,JSON.stringify([{id:'two',name:'Two',content:'Changed after preview'}]));
 assert.throws(()=>service.import('one',selection),/nguồn đã đổi/);assert.equal(service.list('one').entries.length,1);assert.equal(service.list('two').entries.length,0);
 const updated=service.plan('one');assert.equal(service.import('one',{workspaceId:'one',fingerprint:updated.fingerprint,ids:[updated.entries[1].id]}).imported,1);
});

test('custom catalog versions preserve old briefs and reject stale edits across workspaces',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'cos-custom-catalog-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));const service=createCatalogService(root);
 const first=service.save('one',{kind:'prompt',name:'Review',content:'Review source accurately',secret:'excluded'}).entry;
 assert.equal(first.source.app,'contentos');assert.equal(first.payload.secret,undefined);
 const brief=service.brief('one',{promptId:first.id});assert.equal(brief.entries[0].payload.content,'Review source accurately');
 assert.equal(service.save('one',{kind:'prompt',name:'Review',content:first.payload.content,parentId:first.id}).unchanged,true);
 const next=service.save('one',{kind:'prompt',name:'Review v2',content:'Updated review',parentId:first.id}).entry;
 assert.equal(next.version,2);assert.equal(next.source.sourceId,first.source.sourceId);assert.equal(next.parentId,first.id);
 assert.equal(service.brief('one',{promptId:first.id}).entries[0].payload.content,brief.entries[0].payload.content);
 assert.throws(()=>service.save('one',{kind:'prompt',name:'stale',content:'stale',parentId:first.id}),/mới hơn/);
 assert.throws(()=>service.save('two',{kind:'prompt',name:'wrong',content:'wrong',parentId:first.id}),/workspace/);
 assert.throws(()=>service.save('one',{kind:'style',name:'wrong',art:'wrong',parentId:next.id}),/loại/);
 for(const body of [{kind:'skill',name:'wrong',content:'x'},{kind:'prompt',name:'empty',content:''},{kind:'style',name:'x',art:{nested:true}},{kind:'prompt',name:'x',content:'x'.repeat(30001)}])assert.throws(()=>service.save('one',body));
 assert.equal(service.list('one').entries.length,2);assert.equal(service.list('two').entries.length,0);
});
